export function getMockMenu(restaurantId) {
  const restFoods = MOCK_FOODS.filter(
    (f) => !restaurantId || f.restaurant?._id === restaurantId || f.restaurant?.slug === restaurantId
  );
  const pool = restFoods.length >= 3 ? restFoods : MOCK_FOODS;

  const grouped = {};
  pool.forEach((food) => {
    const cat = food.categoryName || 'Recommended';
    if (!grouped[cat]) grouped[cat] = [];
    grouped[cat].push(food);
  });
  return grouped;
}
